"""Radiance ``.cal`` projection function generators.

Five projection modes are supported:

* ``uv``           – mesh UV passthrough (Radiance 6.0, ``Lu``/``Lv``).
* ``planar``       – planar projection on a chosen axis pair.
* ``box``          – triplanar projection driven by surface normal.
* ``cylindrical``  – wraps around the Z axis (columns, pipes).
* ``spherical``    – full spherical mapping (domes, globes).

Functions return the raw ``.cal`` file text.
"""

from __future__ import annotations

from typing import Literal

PlanarAxis = Literal["xy", "xz", "yz"]


_HEADER = (
    "{{ Generated by pbr2rad - projection mode: {mode} }}\n"
    "{{ Arguments exposed to .rad file: u v (data) / pic_u pic_v (picture) }}\n"
)


def _picture_lookup(pic_u_scale: float, pic_v_scale: float) -> str:
    """Emit the colorpict lookup coordinates.

    Radiance maps a WxH picture so that its SHORT side spans [0,1] and its
    long side spans [0, long/short] (``getpict()`` in data.c). ``u``/``v``
    are kept in the unit square for the texdata/brightdata ``.dat`` files,
    which declare ``0 1 N`` on both axes; the picture lookup is scaled by the
    aspect so one tile of ``u``/``v`` covers one full texture. For square
    textures both scales are 1 and ``pic_u``/``pic_v`` equal ``u``/``v``.
    """
    return (
        "{ picture lookup: short side spans 0..1, long side 0..aspect }\n"
        f"pic_u = u * {pic_u_scale:g};\n"
        f"pic_v = v * {pic_v_scale:g};\n"
    )


def uv_passthrough(
    *,
    pic_u_scale: float = 1.0,
    pic_v_scale: float = 1.0,
) -> str:
    """Mesh UV passthrough.  Uses ``Lu``/``Lv`` from the mesh primitive."""
    return (
        _HEADER.format(mode="mesh UV (Lu/Lv)")
        + "u = Lu;\n"
        + "v = Lv;\n"
        + _picture_lookup(pic_u_scale, pic_v_scale)
    )


def planar(
    axis: PlanarAxis = "xy",
    *,
    u_scale: float = 1.0,
    v_scale: float = 1.0,
    u_offset: float = 0.0,
    v_offset: float = 0.0,
    pic_u_scale: float = 1.0,
    pic_v_scale: float = 1.0,
) -> str:
    """Planar projection on ``axis`` (``xy``/``xz``/``yz``).

    Scales in world units: ``u_scale = 1/texture_width_meters``.
    """
    u_src, v_src = {
        "xy": ("Px", "Py"),
        "xz": ("Px", "Pz"),
        "yz": ("Py", "Pz"),
    }[axis]
    return (
        _HEADER.format(mode=f"planar {axis.upper()}")
        + f"u_scale : {u_scale:g};\n"
        + f"v_scale : {v_scale:g};\n"
        + f"u_offset : {u_offset:g};\n"
        + f"v_offset : {v_offset:g};\n"
        + f"u = mod({u_src} * u_scale + u_offset, 1);\n"
        + f"v = mod({v_src} * v_scale + v_offset, 1);\n"
        + _picture_lookup(pic_u_scale, pic_v_scale)
    )


def box(
    *,
    u_scale: float = 1.0,
    v_scale: float = 1.0,
    u_offset: float = 0.0,
    v_offset: float = 0.0,
    pic_u_scale: float = 1.0,
    pic_v_scale: float = 1.0,
) -> str:
    """Triplanar / box projection driven by the dominant normal axis.

    * |Nz| dominant → XY plane
    * |Nx| dominant → YZ plane
    * |Ny| dominant → XZ plane
    """
    return (
        _HEADER.format(mode="box / triplanar")
        + f"u_scale : {u_scale:g};\n"
        + f"v_scale : {v_scale:g};\n"
        + f"u_offset : {u_offset:g};\n"
        + f"v_offset : {v_offset:g};\n"
        + "abs_nx = abs(Nx);\n"
        + "abs_ny = abs(Ny);\n"
        + "abs_nz = abs(Nz);\n"
        + "nx_dom = if(abs_nx - abs_ny, if(abs_nx - abs_nz, 1, 0), 0);\n"
        + "nz_dom = if(abs_nz - abs_nx, if(abs_nz - abs_ny, 1, 0), 0);\n"
        + "{ ny dominant is the remaining case; u source is Py only when }\n"
        + "{ nx dominates - both nz-dominant and ny-dominant read Px }\n"
        + "u_raw = if(nx_dom - 0.5, Py, Px);\n"
        + "v_raw = if(nx_dom - 0.5, Pz, if(nz_dom - 0.5, Py, Pz));\n"
        + "u = mod(u_raw * u_scale + u_offset, 1);\n"
        + "v = mod(v_raw * v_scale + v_offset, 1);\n"
        + _picture_lookup(pic_u_scale, pic_v_scale)
    )


def cylindrical(
    *,
    u_scale: float = 1.0,
    v_scale: float = 1.0,
    u_offset: float = 0.0,
    v_offset: float = 0.0,
    pic_u_scale: float = 1.0,
    pic_v_scale: float = 1.0,
) -> str:
    """Cylindrical projection wrapping around the Z axis.

    ``u`` maps the angle around Z (0..1 = full revolution).
    ``v`` maps the Z height.  Suitable for columns, pipes, and cylinders.
    """
    return (
        _HEADER.format(mode="cylindrical (Z axis)")
        + f"u_scale : {u_scale:g};\n"
        + f"v_scale : {v_scale:g};\n"
        + f"u_offset : {u_offset:g};\n"
        + f"v_offset : {v_offset:g};\n"
        + "{ angle around Z axis, normalised to 0..1 }\n"
        + "u = mod(atan2(Py, Px) / (2*PI) * u_scale + u_offset, 1);\n"
        + "v = mod(Pz * v_scale + v_offset, 1);\n"
        + _picture_lookup(pic_u_scale, pic_v_scale)
    )


def spherical(
    *,
    u_scale: float = 1.0,
    v_scale: float = 1.0,
    u_offset: float = 0.0,
    v_offset: float = 0.0,
    pic_u_scale: float = 1.0,
    pic_v_scale: float = 1.0,
    swap_uv: bool = False,
) -> str:
    """Spherical (equirectangular) projection.

    ``u`` maps longitude (angle around Z).
    ``v`` maps latitude (angle from equator, 0.5 = equator).
    Suitable for domes, globes, and spheres.

    ``swap_uv`` transposes the wrap: ``u`` (the picture's x axis) runs
    pole-to-pole and ``v`` runs around (for spheres whose UVs are laid out
    that way; neither ambientCG's nor Poly Haven's reference spheres are).
    ``u_scale`` / ``v_scale`` always scale ``u`` / ``v`` respectively.
    """
    lon = "atan2(Py, Px) / (2*PI)"
    lat = "asin(Pz / r) / PI"
    if swap_uv:
        u_line = f"u = mod({lat} * u_scale + 0.5 + u_offset, 1);\n"
        v_line = f"v = mod({lon} * v_scale + v_offset, 1);\n"
        mode = "spherical (equirectangular, transposed: u pole-to-pole, v around)"
        note = "{ u: latitude (+0.5 so equator is at u=0.5); v: longitude around Z }\n"
    else:
        u_line = f"u = mod({lon} * u_scale + u_offset, 1);\n"
        v_line = f"v = mod({lat} * v_scale + 0.5 + v_offset, 1);\n"
        mode = "spherical (equirectangular)"
        note = "{ u: longitude around Z; v: latitude (+0.5 so equator is at v=0.5) }\n"
    return (
        _HEADER.format(mode=mode)
        + f"u_scale : {u_scale:g};\n"
        + f"v_scale : {v_scale:g};\n"
        + f"u_offset : {u_offset:g};\n"
        + f"v_offset : {v_offset:g};\n"
        + "{ guard r for the degenerate origin sample }\n"
        + "rr = sqrt(Px*Px + Py*Py + Pz*Pz);\n"
        + "r = if(rr - 1e-6, rr, 1e-6);\n"
        + note
        + u_line
        + v_line
        + _picture_lookup(pic_u_scale, pic_v_scale)
    )


def generate(
    mode: str,
    *,
    u_scale: float = 1.0,
    v_scale: float = 1.0,
    u_offset: float = 0.0,
    v_offset: float = 0.0,
    axis: PlanarAxis = "xy",
    pic_u_scale: float = 1.0,
    pic_v_scale: float = 1.0,
    swap_uv: bool = False,
) -> str:
    """Dispatch helper used by the CLI.

    ``pic_u_scale``/``pic_v_scale`` are the albedo picture's aspect factors
    (``max(1, w/h)`` and ``max(1, h/w)``) — see ``_picture_lookup``.
    ``swap_uv`` only applies to ``spherical`` (transposed wrap).
    """
    pic = dict(pic_u_scale=pic_u_scale, pic_v_scale=pic_v_scale)
    if mode == "uv":
        return uv_passthrough(**pic)
    if mode == "planar":
        return planar(
            axis,
            u_scale=u_scale,
            v_scale=v_scale,
            u_offset=u_offset,
            v_offset=v_offset,
            **pic,
        )
    if mode == "box":
        return box(
            u_scale=u_scale, v_scale=v_scale,
            u_offset=u_offset, v_offset=v_offset, **pic,
        )
    if mode == "cylindrical":
        return cylindrical(
            u_scale=u_scale, v_scale=v_scale,
            u_offset=u_offset, v_offset=v_offset, **pic,
        )
    if mode == "spherical":
        return spherical(
            u_scale=u_scale, v_scale=v_scale,
            u_offset=u_offset, v_offset=v_offset, swap_uv=swap_uv, **pic,
        )
    raise ValueError(f"unknown projection mode: {mode!r}")


# ---------------------------------------------------------------------------
# Tangent frame (for normal maps)
# ---------------------------------------------------------------------------
#
# A tangent-space normal map says how far the surface normal leans along the
# texture's own axes: red along +u, green along +v, blue along the normal.
# Radiance's texdata/texfunc add their perturbation vector to the normal in
# WORLD axes (there is no transform on the modifier), so the normal .cal has
# to turn the map's (x, y, z) into world directions itself. Until 2026-11-10
# it added the map's x/y/z straight onto world X/Y/Z, which is right only on
# surfaces facing +Z: on a wall the map's green channel pushed along the
# wall's own normal (invisible) and its blue channel tilted every bump down.
#
# ``tangent_frame`` emits, for a projection, the unit vectors on the surface
# along which u grows (``nm_tx/ty/tz``) and v grows (``nm_bx/by/bz``):
#   B = v's gradient, projected into the surface plane;
#   T = u's gradient in the plane, made perpendicular to B (the bitangent
#       convention of MikkTSpace, which most normal maps are baked against).
# Where u or v does not change across a surface (a planar projection seen
# edge-on, a cylinder's caps) the missing axis is completed from the other
# and the normal, so the frame is always defined. The raw gradient
# directions per mode come from the u/v formulas above; a negative scale
# flips its axis. ``uv`` (mesh Lu/Lv) carries no direction information in
# Radiance, so it falls back to the box projection's frame: correct for
# meshes whose UVs run the way a box projection would lay them out.

def _frame_axes(mode: str, axis: PlanarAxis, swap_uv: bool) -> tuple[str, tuple[str, str, str], tuple[str, str, str]]:
    """Setup lines plus the raw (unnormalised) world gradients of u and v."""
    if mode == "planar":
        t, b = {"xy": ("100", "010"), "xz": ("100", "001"), "yz": ("010", "001")}[axis]
        vec = lambda s: tuple(s)  # noqa: E731
        return "", vec(t), vec(b)
    if mode in ("box", "uv"):
        setup = (
            "nm_ax = abs(Nx);\n"
            "nm_ay = abs(Ny);\n"
            "nm_az = abs(Nz);\n"
            "nm_xdom = if(nm_ax - nm_ay, if(nm_ax - nm_az, 1, 0), 0);\n"
            "nm_zdom = if(nm_az - nm_ax, if(nm_az - nm_ay, 1, 0), 0);\n"
            "{ X dominant: u=Py v=Pz; Z dominant: u=Px v=Py; Y dominant: u=Px v=Pz }\n"
        )
        t = ("if(nm_xdom - 0.5, 0, 1)", "if(nm_xdom - 0.5, 1, 0)", "0")
        b = ("0", "if(nm_zdom - 0.5, 1, 0)", "if(nm_zdom - 0.5, 0, 1)")
        return setup, t, b
    east = ("-Py", "Px", "0")                             # longitude / angle around Z grows
    if mode == "cylindrical":
        return "", east, ("0", "0", "1")
    if mode == "spherical":
        north = ("-Px*Pz", "-Py*Pz", "Px*Px + Py*Py")    # latitude grows
        return ("", north, east) if swap_uv else ("", east, north)
    raise ValueError(f"unknown projection mode: {mode!r}")


def tangent_frame(
    mode: str,
    *,
    axis: PlanarAxis = "xy",
    u_scale: float = 1.0,
    v_scale: float = 1.0,
    swap_uv: bool = False,
) -> str:
    """``.cal`` lines defining the unit tangent ``nm_tx/ty/tz`` (u grows) and
    bitangent ``nm_bx/by/bz`` (v grows) on the surface at the hit point, for
    the projection ``mode`` (see the notes above)."""
    setup, t, b = _frame_axes(mode, axis, swap_uv)
    su = -1 if (u_scale < 0 and mode != "uv") else 1
    sv = -1 if (v_scale < 0 and mode != "uv") else 1

    def signed(expr: str, s: int) -> str:
        if expr in ("0", "1"):
            return "0" if expr == "0" else str(s)
        return expr if s == 1 else f"-({expr})"

    t = tuple(signed(c, su) for c in t)
    b = tuple(signed(c, sv) for c in b)
    mode_note = "box projection's frame (mesh UVs carry no direction)" if mode == "uv" else f"{mode}"
    return (
        f"{{ Tangent frame for the normal map ({mode_note}): }}\n"
        "{ nm_t* = direction on the surface in which u grows, nm_b* = v grows }\n"
        + setup
        + f"nm_rtx = {t[0]};\nnm_rty = {t[1]};\nnm_rtz = {t[2]};\n"
        + f"nm_rbx = {b[0]};\nnm_rby = {b[1]};\nnm_rbz = {b[2]};\n"
        "{ both into the surface plane }\n"
        "nm_tn = nm_rtx*Nx + nm_rty*Ny + nm_rtz*Nz;\n"
        "nm_t1x = nm_rtx - nm_tn*Nx;\n"
        "nm_t1y = nm_rty - nm_tn*Ny;\n"
        "nm_t1z = nm_rtz - nm_tn*Nz;\n"
        "nm_tl = sqrt(nm_t1x*nm_t1x + nm_t1y*nm_t1y + nm_t1z*nm_t1z);\n"
        "nm_bn = nm_rbx*Nx + nm_rby*Ny + nm_rbz*Nz;\n"
        "nm_b1x = nm_rbx - nm_bn*Nx;\n"
        "nm_b1y = nm_rby - nm_bn*Ny;\n"
        "nm_b1z = nm_rbz - nm_bn*Nz;\n"
        "nm_bl = sqrt(nm_b1x*nm_b1x + nm_b1y*nm_b1y + nm_b1z*nm_b1z);\n"
        "{ B: v's direction; where v does not change across the surface, N x T }\n"
        "nm_tlg = if(nm_tl - 1e-9, nm_tl, 1e-9);\n"
        "nm_bx = if(nm_bl - 1e-6, nm_b1x/nm_bl, (Ny*nm_t1z - Nz*nm_t1y)/nm_tlg);\n"
        "nm_by = if(nm_bl - 1e-6, nm_b1y/nm_bl, (Nz*nm_t1x - Nx*nm_t1z)/nm_tlg);\n"
        "nm_bz = if(nm_bl - 1e-6, nm_b1z/nm_bl, (Nx*nm_t1y - Ny*nm_t1x)/nm_tlg);\n"
        "{ T: u's direction made perpendicular to B; where u does not change, B x N }\n"
        "nm_tb = nm_t1x*nm_bx + nm_t1y*nm_by + nm_t1z*nm_bz;\n"
        "nm_t2x = nm_t1x - nm_tb*nm_bx;\n"
        "nm_t2y = nm_t1y - nm_tb*nm_by;\n"
        "nm_t2z = nm_t1z - nm_tb*nm_bz;\n"
        "nm_t2l = sqrt(nm_t2x*nm_t2x + nm_t2y*nm_t2y + nm_t2z*nm_t2z);\n"
        "nm_tx = if(nm_t2l - 1e-6, nm_t2x/nm_t2l, nm_by*Nz - nm_bz*Ny);\n"
        "nm_ty = if(nm_t2l - 1e-6, nm_t2y/nm_t2l, nm_bz*Nx - nm_bx*Nz);\n"
        "nm_tz = if(nm_t2l - 1e-6, nm_t2z/nm_t2l, nm_bx*Ny - nm_by*Nx);\n"
    )


def picture_scales(width: int, height: int) -> tuple[float, float]:
    """Aspect factors for ``pic_u``/``pic_v`` from the albedo's pixel size."""
    if width <= 0 or height <= 0:
        return 1.0, 1.0
    return max(1.0, width / height), max(1.0, height / width)
